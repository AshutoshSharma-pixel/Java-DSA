//to print the sum of the first n natural numbers n = 4.
package Loops;

public class question_loops {
    public static void main(String[] args) {
        int n = 100;
        int sum = 0;
        for (int i = 0; i<=100;i++){
            sum = 0 +i;
            System.out.println(sum);
        }
        System.out.println("Sum of first " + n + " natural numbers is: " + sum);
    }
}
